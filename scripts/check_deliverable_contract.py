#!/usr/bin/env python3
r"""Delivery gate: the full-text `.docx` the venue asked for actually exists.

Why this exists
---------------
`assemble_manuscript_docx.py` *writes* the Word deliverable. This checker is the
read-only counterpart, and the split is deliberate for the same reason
`check_table_style.py` is separate from `make_three_line_tables.py`: a gate that
only asks "did our own writer run?" proves nothing about a file someone
regenerated by hand, converted in Word, or copied in from a co-author.

So everything here is re-derived from the shipped artifact:

  - the file exists at the path the run declared;
  - it carries **at least as many tables and figures as the manuscript includes**
    — the silent-drop failure mode, where a conversion loses an exhibit and the
    paper ships a result nobody can see;
  - it contains real prose, not just floating exhibits;
  - it has no leftover `\input{}`, `??` cross-reference, citation placeholder or
    assembler `[UNRESOLVED …]` marker;
  - and the state file's claims about it are not greener than the file on disk.

The last one matters most. `manuscript.docx_status = verified` is a claim, and
until this checker exists nothing stopped a run from writing it beside a `.docx`
that was never built.

Not every run owes a Word file. A venue that takes LaTeX only sets
`manuscript.docx_status = not-required`, which is honoured — but it must be
*declared*, not inferred from the file's absence.

Usage:
    python3 scripts/check_deliverable_contract.py <workspace>
    python3 scripts/check_deliverable_contract.py <workspace> --json
    python3 scripts/check_deliverable_contract.py <workspace> --strict
    python3 scripts/check_deliverable_contract.py --selftest

Exit code is non-zero iff a hard violation is found.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tempfile
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from assemble_manuscript_docx import (  # noqa: E402  (path set above by design)
    CHAIN,
    count_docx_exhibits,
    docx_text,
    find_source,
    parse_body,
    scan_unresolved,
)

FAIL = "FAIL"
WARN = "WARN"
INFO = "INFO"
OKAY = "OK"

# The prose floor is expressed in *English-equivalent* characters. A CJK codepoint
# carries roughly the information of an English word, so a genuine Chinese section
# that would clear this bar in English is only ~a quarter as many characters. A
# floor calibrated on English alone rejects real 中文 manuscripts, which is the
# opposite of what this check is for.
MIN_PROSE_CHARS = 400
CJK_WEIGHT = 3.5
MIN_PROSE_LINE_CHARS = 20
NOT_REQUIRED = "not-required"
VALID_STATUS = {"pending", "assembled", "verified", NOT_REQUIRED}


class Report:
    def __init__(self) -> None:
        self.rows: list[tuple[str, str, str]] = []

    def add(self, level: str, check: str, detail: str) -> None:
        self.rows.append((level, check, detail))

    @property
    def failures(self) -> list[tuple[str, str, str]]:
        return [r for r in self.rows if r[0] == FAIL]

    def to_dict(self) -> dict:
        return {"ok": not self.failures,
                "checks": [{"level": l, "check": c, "detail": d} for l, c, d in self.rows]}

    def render(self) -> str:
        width = max((len(c) for _, c, _ in self.rows), default=4)
        lines = ["", "Paper-WorkFlow deliverable contract", "=" * 64]
        for level, check, detail in self.rows:
            lines.append(f"[{level:<4}] {check:<{width}}  {detail}")
        lines.append("=" * 64)
        if self.failures:
            lines.append(f"RESULT: {len(self.failures)} hard violation(s) -> deliverable NOT verified")
        else:
            lines.append("RESULT: the deliverable the venue asked for is on disk and complete")
        return "\n".join(lines)


# --------------------------------------------------------------------------- #
# helpers                                                                      #
# --------------------------------------------------------------------------- #
def load_state(workspace: Path) -> dict:
    for rel in ("00_meta/workflow_state.json", "workflow_state.json"):
        path = workspace / rel
        if path.is_file():
            try:
                return json.loads(path.read_text(encoding="utf-8"))
            except json.JSONDecodeError:
                return {}
    return {}


def expected_exhibits(workspace: Path) -> tuple[int, int, str]:
    """(tables, figures, source) the manuscript body asks for."""
    source = find_source(workspace)
    if source is None:
        return 0, 0, ""
    blocks = parse_body(source)
    tables = sum(1 for b in blocks if b.kind in {"table", "include_table"})
    figures = sum(1 for b in blocks if b.kind == "include_figure")
    return tables, figures, str(source.relative_to(workspace))


def _is_cjk(ch: str) -> bool:
    code = ord(ch)
    return (0x3400 <= code <= 0x9FFF          # CJK unified ideographs (+ ext A)
            or 0xF900 <= code <= 0xFAFF       # compatibility ideographs
            or 0x3040 <= code <= 0x30FF       # kana
            or 0xAC00 <= code <= 0xD7AF)      # hangul syllables


def prose_chars(text: str) -> int:
    """English-equivalent characters of running prose.

    Short lines are dropped because table cells and captions arrive as their own
    paragraphs; CJK codepoints are weighted up so the same floor means the same
    amount of writing in Chinese as in English.
    """
    total = 0.0
    for raw in text.splitlines():
        line = raw.strip()
        if len(line) < MIN_PROSE_LINE_CHARS:
            continue
        total += sum(CJK_WEIGHT if _is_cjk(ch) else 1 for ch in line)
    return int(total)


# --------------------------------------------------------------------------- #
# checks                                                                       #
# --------------------------------------------------------------------------- #
def evaluate(workspace: Path, *, strict: bool = False) -> Report:
    rep = Report()
    if not workspace.is_dir():
        rep.add(FAIL, "workspace", f"workspace not found: {workspace}")
        return rep

    state = load_state(workspace)
    manuscript = state.get("manuscript") if isinstance(state.get("manuscript"), dict) else {}
    if not manuscript:
        rep.add(INFO, "state",
                "no manuscript block in workflow_state.json (schema < 14) — "
                "deliverable contract not yet declared")
        return rep

    status = str(manuscript.get("docx_status") or "pending")
    if status not in VALID_STATUS:
        rep.add(FAIL, "state:status",
                f"manuscript.docx_status={status!r} is not one of {sorted(VALID_STATUS)}")
        return rep

    fmt = str(manuscript.get("format") or "")
    if fmt not in {"latex", "markdown"}:
        rep.add(WARN, "state:format",
                f"manuscript.format={fmt!r} is undeclared; Stage 0 should pin it to "
                "'latex' or 'markdown' (Word-bound runs should author in markdown)")

    if status == NOT_REQUIRED:
        rep.add(INFO, "scope",
                "manuscript.docx_status=not-required — this venue takes LaTeX only; "
                "no Word deliverable is owed")
        if str(manuscript.get("deliverable") or "") == "docx":
            rep.add(FAIL, "scope:contradiction",
                    "manuscript.deliverable=docx but docx_status=not-required — the run "
                    "both owes and disclaims the Word file")
        return rep

    rel = str(manuscript.get("deliverable_docx") or "09_submission/main.docx")
    path = workspace / rel

    want_tables, want_figures, source = expected_exhibits(workspace)
    if source:
        rep.add(INFO, "source", f"{source}: {want_tables} exhibit include(s), {want_figures} figure(s)")

    if not path.is_file():
        level = FAIL if (strict or status in {"assembled", "verified"}) else WARN
        rep.add(level, "deliverable",
                f"{rel} does not exist — build it with "
                f"`python3 scripts/assemble_manuscript_docx.py {workspace}`"
                + ("" if level == FAIL else " (advisory until --strict or docx_status advances)"))
        return rep

    try:
        with zipfile.ZipFile(path) as archive:
            if "word/document.xml" not in archive.namelist():
                rep.add(FAIL, "deliverable", f"{rel} is a zip but not a Word document")
                return rep
    except (OSError, zipfile.BadZipFile):
        rep.add(FAIL, "deliverable", f"{rel} is not a readable .docx")
        return rep

    tables, figures = count_docx_exhibits(path)
    text = docx_text(path)

    rep.add(OKAY, "deliverable", f"{rel}: {tables} table(s), {figures} figure(s), {len(text)} chars of text")

    if want_tables and tables < want_tables:
        rep.add(FAIL, "exhibits:tables",
                f"{rel} carries {tables} table(s) but the manuscript includes {want_tables} — "
                "exhibit(s) were lost in conversion; re-run the assembler and check its "
                "unresolved-marker report")
    elif want_tables:
        rep.add(OKAY, "exhibits:tables", f"all {want_tables} manuscript exhibit(s) present in the .docx")

    if want_figures and figures < want_figures:
        rep.add(FAIL, "exhibits:figures",
                f"{rel} carries {figures} figure(s) but the manuscript includes {want_figures} — "
                "figure(s) were lost in conversion (a .pdf-only figure cannot be embedded; "
                "export a .png alongside it)")
    elif want_figures:
        rep.add(OKAY, "exhibits:figures", f"all {want_figures} manuscript figure(s) present in the .docx")

    body = prose_chars(text)
    if body < MIN_PROSE_CHARS:
        rep.add(FAIL if strict else WARN, "prose",
                f"{rel} holds only {body} chars of running prose — a deliverable that is "
                "exhibits with no paper around them is a conversion failure, not a manuscript"
                + ("" if strict else " (advisory until --strict)"))
    else:
        rep.add(OKAY, "prose", f"{body} chars of running prose")

    leftovers = scan_unresolved(text)
    if leftovers:
        rep.add(FAIL, "unresolved",
                f"{rel} still contains: " + "; ".join(leftovers)
                + " — fix the source or the exhibit path, then re-assemble")
    else:
        rep.add(OKAY, "unresolved", "no unresolved includes, cross-references or placeholders")

    # State honesty: the file on disk is the authority, the state file is a claim.
    declared = manuscript.get("unresolved_markers")
    if isinstance(declared, list) and not declared and leftovers:
        rep.add(FAIL, "state:markers",
                "manuscript.unresolved_markers is empty but the .docx still carries "
                f"{len(leftovers)} unresolved marker class(es)")
    for key, actual, label in (("exhibits_embedded", tables, "table"),
                               ("figures_embedded", figures, "figure")):
        claimed = manuscript.get(key)
        if isinstance(claimed, int) and claimed > actual:
            rep.add(FAIL, f"state:{key}",
                    f"state claims {claimed} embedded {label}(s) but the .docx has {actual}")

    if status == "verified" and rep.failures:
        rep.add(FAIL, "state:verified",
                "manuscript.docx_status=verified while this gate is red — a verified claim "
                "must be earned by the artifact, not written into state")
    elif status == "verified":
        rep.add(OKAY, "state:verified", "docx_status=verified is consistent with the artifact")
    elif not rep.failures:
        rep.add(INFO, "state:verified",
                f"docx_status={status!r}: every check passed, so this run may now set "
                "manuscript.docx_status=verified")

    pack = state.get("replication_pack") if isinstance(state.get("replication_pack"), dict) else {}
    if str(pack.get("status") or "") == "ready" and status not in {"verified", NOT_REQUIRED}:
        rep.add(FAIL, "ordering:replication_pack",
                f"replication_pack.status=ready while manuscript.docx_status={status!r} — "
                "a submission package cannot be ready while the deliverable it ships is "
                "unbuilt or unchecked")

    return rep


