_TEX = r"""
\documentclass{article}
\begin{document}
\section{Results}
The treatment raises log wages by 0.123 (s.e. 0.041), a magnitude that is large
relative to the sample mean and stable across every specification we estimate in
this section, including the ones that absorb region-by-year variation entirely.
\begin{table}[htbp]
\caption{Main results}
\input{results/table2}
\end{table}
\section{Conclusion}
The effect is robust to the full battery of alternative specifications reported
in the appendix, and it survives the placebo tests described immediately above.
Taken together, the evidence points to a single channel rather than the bundle of
mechanisms an earlier literature proposed, and the magnitude is stable whether the
comparison group is built from never-treated units or from not-yet-treated ones.
\end{document}
"""

_TABLE = r"""
\begin{tabular}{lc}
\toprule
Variable & (1) \\
\midrule
treat & 0.123*** \\
N & 12,345 \\
\bottomrule
\end{tabular}
"""


def _workspace(root: Path, *, state: dict) -> Path:
    ws = root / "ws"
    for rel in ("05_draft", "04_results", "09_submission", "00_meta"):
        (ws / rel).mkdir(parents=True, exist_ok=True)
    (ws / "05_draft" / "main.tex").write_text(_TEX, encoding="utf-8")
    (ws / "04_results" / "table2.tex").write_text(_TABLE, encoding="utf-8")
    (ws / "00_meta" / "workflow_state.json").write_text(
        json.dumps(state, ensure_ascii=False), encoding="utf-8")
    return ws


def _base_state(**manuscript: object) -> dict:
    block = {"format": "latex", "deliverable": "docx",
             "deliverable_docx": "09_submission/main.docx", "docx_status": "pending",
             "converter": "", "reference_docx": "", "csl": "",
             "exhibits_embedded": 0, "figures_embedded": 0,
             "unresolved_markers": [], "last_assembly": ""}
    block.update(manuscript)
    return {"schema_version": 14, "manuscript": block}


def _levels(rep: Report, prefix: str) -> list[str]:
    return [lvl for lvl, chk, _ in rep.rows if chk.startswith(prefix)]


def selftest() -> None:
    import assemble_manuscript_docx as assembler

    failures: list[str] = []

    def check(condition: bool, message: str) -> None:
        if not condition:
            failures.append(message)

    # 1. A real assembled deliverable passes.
    with tempfile.TemporaryDirectory(prefix="pw-deliv-ok-") as tmp:
        ws = _workspace(Path(tmp), state=_base_state())
        assembler.run(ws, converter="builtin")
        rep = evaluate(ws, strict=True)
        check(not rep.failures, "a correctly assembled deliverable was rejected: "
                                + "; ".join(f"{c}:{d}" for _, c, d in rep.failures))

    # 2. A missing .docx is a hard failure once the run claims it was assembled.
    with tempfile.TemporaryDirectory(prefix="pw-deliv-missing-") as tmp:
        ws = _workspace(Path(tmp), state=_base_state(docx_status="assembled"))
        rep = evaluate(ws)
        check(FAIL in _levels(rep, "deliverable"),
              "a claimed-but-absent deliverable did not fail")

    # 3. A dropped exhibit is caught by recounting, not by trusting state.
    with tempfile.TemporaryDirectory(prefix="pw-deliv-drop-") as tmp:
        ws = _workspace(Path(tmp), state=_base_state())
        assembler.run(ws, converter="builtin")
        docx = ws / "09_submission" / "main.docx"
        with zipfile.ZipFile(docx) as archive:
            parts = {n: archive.read(n) for n in archive.namelist()}
        stripped = re.sub(rb"<w:tbl>.*?</w:tbl>", b"", parts["word/document.xml"], flags=re.DOTALL)
        parts["word/document.xml"] = stripped
        with zipfile.ZipFile(docx, "w", zipfile.ZIP_DEFLATED) as archive:
            for name, data in parts.items():
                archive.writestr(name, data)
        rep = evaluate(ws)
        check(FAIL in _levels(rep, "exhibits:tables"),
              "a table dropped from the .docx was not detected")

    # 4. A leftover unresolved marker blocks the gate.
    with tempfile.TemporaryDirectory(prefix="pw-deliv-unres-") as tmp:
        ws = _workspace(Path(tmp), state=_base_state())
        (ws / "04_results" / "table2.tex").unlink()
        assembler.run(ws, converter="builtin")
        rep = evaluate(ws)
        check(FAIL in _levels(rep, "unresolved"),
              "an [UNRESOLVED …] marker in the .docx did not fail the gate")

    # 5. `verified` cannot be asserted over a red artifact.
    with tempfile.TemporaryDirectory(prefix="pw-deliv-lie-") as tmp:
        ws = _workspace(Path(tmp), state=_base_state(docx_status="verified"))
        rep = evaluate(ws)
        check(FAIL in _levels(rep, "deliverable") or FAIL in _levels(rep, "state:verified"),
              "docx_status=verified passed with no .docx on disk")

    # 6. A declared not-required venue is honoured.
    with tempfile.TemporaryDirectory(prefix="pw-deliv-na-") as tmp:
        ws = _workspace(Path(tmp), state=_base_state(docx_status="not-required", deliverable="tex"))
        rep = evaluate(ws, strict=True)
        check(not rep.failures, "an explicitly not-required deliverable was rejected")

    # 7. …but not when the same run also says it owes a .docx.
    with tempfile.TemporaryDirectory(prefix="pw-deliv-contra-") as tmp:
        ws = _workspace(Path(tmp), state=_base_state(docx_status="not-required", deliverable="docx"))
        rep = evaluate(ws)
        check(FAIL in _levels(rep, "scope:contradiction"),
              "a run that both owes and disclaims the Word file was not flagged")

    # 8. A ready replication pack requires a settled deliverable.
    with tempfile.TemporaryDirectory(prefix="pw-deliv-order-") as tmp:
        state = _base_state(docx_status="assembled")
        state["replication_pack"] = {"status": "ready"}
        ws = _workspace(Path(tmp), state=state)
        assembler.run(ws, converter="builtin")
        # the assembler resets docx_status to "assembled"; that is the point
        rep = evaluate(ws)
        check(FAIL in _levels(rep, "ordering:replication_pack"),
              "replication_pack=ready passed over an unverified deliverable")

    # 9. A deliverable that is exhibits with no paper around them fails --strict.
    with tempfile.TemporaryDirectory(prefix="pw-deliv-prose-") as tmp:
        ws = _workspace(Path(tmp), state=_base_state())
        (ws / "05_draft" / "main.tex").write_text(
            "\\documentclass{article}\n\\begin{document}\n"
            "\\begin{table}\\caption{Main}\\input{results/table2}\\end{table}\n"
            "\\end{document}\n", encoding="utf-8")
        assembler.run(ws, converter="builtin")
        rep = evaluate(ws, strict=True)
        check(FAIL in _levels(rep, "prose"),
              "a .docx with no running prose passed --strict")
        rep_lenient = evaluate(ws, strict=False)
        check(WARN in _levels(rep_lenient, "prose"),
              "the prose floor should stay advisory without --strict")

    # 9b. A Chinese manuscript of equivalent substance must clear the same floor.
    #     The floor is English-calibrated; without CJK weighting this is a false
    #     positive on every 中文期刊 run, which is most of this skill's traffic.
    zh = ("本文利用某项试点政策的分批推行，识别其对企业全要素生产率的因果效应。"
          "基准估计显示，政策使处理组企业的对数产出显著提高，且效应在政策实施后"
          "逐年增强，事件研究图未显示任何预期效应，平行趋势假设在政策实施前各期"
          "均无法被拒绝。\n"
          "机制检验表明，效应主要通过缓解融资约束而非降低要素成本实现。结论对剔除"
          "最大省份、替换聚类层级、改变窗口宽度与一系列安慰剂检验均保持稳健，异质性"
          "分析显示效应集中于民营企业与制造业企业。")
    assert prose_chars(zh) >= MIN_PROSE_CHARS, (
        f"a real Chinese section scored {prose_chars(zh)} < {MIN_PROSE_CHARS}: "
        "the prose floor is rejecting 中文 manuscripts")
    check(prose_chars("| treat | 0.12 |\n| N | 100 |") < MIN_PROSE_CHARS,
          "table cells alone should not count as running prose")

    # 10. State cannot claim more exhibits than the file holds.
    with tempfile.TemporaryDirectory(prefix="pw-deliv-claim-") as tmp:
        ws = _workspace(Path(tmp), state=_base_state())
        assembler.run(ws, converter="builtin")
        path = ws / "00_meta" / "workflow_state.json"
        state = json.loads(path.read_text(encoding="utf-8"))
        state["manuscript"]["exhibits_embedded"] = 99
        path.write_text(json.dumps(state, ensure_ascii=False), encoding="utf-8")
        rep = evaluate(ws)
        check(FAIL in _levels(rep, "state:exhibits_embedded"),
              "an inflated exhibits_embedded claim was not caught")

    if failures:
        print("FAIL: check_deliverable_contract selftest\n  - " + "\n  - ".join(failures),
              file=sys.stderr)
        raise SystemExit(1)
    print("selftest OK: deliverable-contract invariants hold")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="check_deliverable_contract.py",
        description="Verify that the full-text .docx deliverable exists, carries every "
                    "exhibit the manuscript includes, and is not over-claimed in state.",
        epilog="Build it first with scripts/assemble_manuscript_docx.py.",
    )
    parser.add_argument("workspace", nargs="?", help="paper workspace root")
    parser.add_argument("--strict", action="store_true",
                        help="advisory tiers become hard failures (Stage 9)")
    parser.add_argument("--json", action="store_true", help="machine-readable output")
    parser.add_argument("--selftest", action="store_true", help="verify this checker")
    args = parser.parse_args(argv)

    if args.selftest:
        selftest()
        return 0
    if not args.workspace:
        parser.error("workspace is required (or pass --selftest)")

    rep = evaluate(Path(args.workspace).expanduser().resolve(), strict=args.strict)
    print(json.dumps(rep.to_dict(), ensure_ascii=False, indent=2) if args.json else rep.render())
    return 1 if rep.failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
